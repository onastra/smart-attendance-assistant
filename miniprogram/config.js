// 后端服务地址配置 —— 三种场景填三种值，别混用：
// 1. 微信开发者工具模拟器：保持 localhost 即可（需在「详情 → 本地设置」勾选
//    「不校验合法域名、web-view（业务域名）、TLS 版本以及 HTTPS 证书」，
//    不勾的话微信会拦掉所有 http://localhost 请求）。
// 2. 真机预览：改成电脑的局域网 IP，例如 http://192.168.1.100:8080，
//    手机与电脑必须连同一个 Wi-Fi，且同样勾选上面的"不校验合法域名"。
// 3. ⚠️ 端口必须改成你自己后端实际占用的端口（默认 8080）。
//    若 8080 被其它服务（如 tomcat）占用而你用 --server.port=8088 启动后端，
//    这里就要同步改成 8088，否则小程序所有请求都会失败。
//
// ============================================================
// 📦 发布前（上传代码 / 提交审核）必须改成线上 HTTPS 域名：
//      const BASE_URL = 'https://your-domain.com'
//    微信的硬性要求（缺一不可，否则线上所有请求失败）：
//      · 必须是 https，不能是 http、localhost 或裸 IP
//      · 域名必须已 ICP 备案（中国大陆）
//      · 微信公众平台 → 开发 → 开发管理 → 开发设置 → 服务器域名，
//        把这个域名加进「request 合法域名」并保存（每月只能改几次，谨慎）
//    也就是说：小程序能发布 ≠ 能用，后端还得先部署到公网 HTTPS 上。
// ============================================================
const BASE_URL = 'http://localhost:8080'

module.exports = {
  BASE_URL: BASE_URL
}
