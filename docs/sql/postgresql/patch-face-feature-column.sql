-- ============================================================
--  人脸特征列扩容（arcsoft 真实特征需要约 1.4KB）
-- ------------------------------------------------------------
--  背景：noop 模拟实现存的是 SHA-256 指纹（64 字符），
--        VARCHAR(128) 够用；切换到虹软 SDK 后特征向量 1032 字节，
--        Base64 编码约 1376 字符，原列宽会直接截断/报错。
--  幂等：反复执行无副作用。
-- ============================================================

ALTER TABLE face_feature ALTER COLUMN feature_hash TYPE TEXT;

COMMENT ON COLUMN face_feature.feature_hash IS
  '人脸特征：noop=图片指纹哈希（64 字符）；arcsoft=Base64 编码的虹软特征向量（约 1.4KB）。单向不可逆，不保存原图。';
