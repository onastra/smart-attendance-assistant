-- =============================================================
-- 联智·企业级 AI Agent 智能考勤与业务助手 —— PostgreSQL 初始化脚本
-- 目标版本：PostgreSQL 15+（Supabase 实测 PG 17）
-- 说明：
--   1) 本脚本对应 MySQL 版 schema.sql + patch-phase2~6 + patch-phaseE 的
--      合并结果（补丁中的列、索引、权限码已全部内联），一次执行即为最终结构。
--   2) 使用 DROP TABLE IF EXISTS ... CASCADE，可重复执行；再次执行会清空业务数据。
--   3) 表之间不建物理外键，关联校验在应用层完成，与 MySQL 版保持一致。
--   4) MySQL 的 ON UPDATE CURRENT_TIMESTAMP 由触发器 set_updated_at() 等价实现。
--   5) 知识库全文检索：MySQL ngram 全文索引 → pg_trgm 三元组 GIN 索引。
-- =============================================================

-- 中文/模糊检索用扩展（Supabase 已内置）
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- updated_at 自动维护触发器（等价 MySQL 的 ON UPDATE CURRENT_TIMESTAMP）
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

